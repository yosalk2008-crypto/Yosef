"""
Builds lib/data/kennzahlen.ts from the CIA World Factbook (public domain), via the JSON mirror
https://github.com/factbook/factbook.json (clone it and pass the folder as first argument).

Countries are matched by their internet country code (.de -> de -> DEU).

    python3 scripts/data/factbook.py /path/to/factbook.json
"""
import glob
import json
import os
import re
import sys

SRC = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
countries = json.load(open(os.path.join(ROOT, "lib/data/countries.json")))
by_iso2 = {c["iso2"]: c["id"] for c in countries}
TLD_FIX = {"uk": "gb"}
NAME_FIX = {"Kosovo": "XKX"}


def get(d, *path):
    for p in path:
        if not isinstance(d, dict):
            return None
        d = d.get(p)
    if isinstance(d, dict) and "text" in d:
        return d["text"]
    return d


def num(s, unit=None):
    """First number in s (optionally the one right before `unit`)."""
    if not s:
        return None
    s = re.sub(r"<[^>]+>", " ", s)
    if unit:
        m = re.search(r"(-?[\d,]+(?:\.\d+)?)\s*" + re.escape(unit), s)
    else:
        m = re.search(r"-?[\d,]+(?:\.\d+)?", s)
    if not m:
        return None
    txt = m.group(1) if unit else m.group(0)
    try:
        return float(txt.replace(",", ""))
    except ValueError:
        return None


def latest(d):
    """Economy fields keyed by year: take the newest one."""
    if not isinstance(d, dict):
        return None
    keys = sorted([k for k in d if re.search(r"\d{4}$", k)], reverse=True)
    return get(d, keys[0]) if keys else get(d)


out = {}
for f in sorted(glob.glob(os.path.join(SRC, "*", "*.json"))):
    if "/meta/" in f or "/oceans/" in f:
        continue
    d = json.load(open(f))
    tld = (get(d, "Communications", "Internet country code") or "").strip()
    m = re.search(r"\.([a-z]{2})\b", tld)
    iso3 = None
    if m:
        iso3 = by_iso2.get(TLD_FIX.get(m.group(1), m.group(1)))
    name = get(d, "Government", "Country name", "conventional short form")
    if not iso3 and name in NAME_FIX:
        iso3 = NAME_FIX[name]
    if not iso3:
        continue
    g, p, t, e = d.get("Geography", {}), d.get("People and Society", {}), d.get("Transportation", {}), d.get("Economy", {})
    row = {
        "elev": num(get(g, "Elevation", "highest point"), "m") or num(get(g, "Elevation", "highest point")),
        "meanElev": num(get(g, "Elevation", "mean elevation"), "m"),
        "coast": num(get(g, "Coastline"), "km"),
        "birth": num(get(p, "Birth rate")),
        "age": num(get(p, "Median age", "total")),
        "alc": num(get(p, "Alcohol consumption per capita", "total")),
        "obes": num(get(p, "Obesity - adult prevalence rate")),
        "smoke": num(get(p, "Tobacco use", "total")),
        "fert": num(get(p, "Total fertility rate")),
        "docs": num(get(p, "Physician density")),
        "net": num(get(d, "Communications", "Internet users", "percent of population")),
        "airports": num(get(t, "Airports")),
        "rail": num(get(t, "Railways", "total"), "km"),
        "unemp": num(latest(e.get("Unemployment rate"))),
    }
    row = {k: v for k, v in row.items() if v is not None}
    # Factbook lists some landlocked coasts as "0 km (landlocked)"; keep the 0
    out[iso3] = row

missing = [c["id"] for c in countries if c["id"] not in out]
print("matched", len(out), "missing", missing, file=sys.stderr)

lines = [
    "/**",
    " * Extra country figures for Spitzenplatz and the country pages. Source: CIA World Factbook",
    " * (public domain, estimates 2016–2025), via github.com/factbook/factbook.json.",
    " * Generated by scripts/data/factbook.py – do not edit by hand.",
    " */",
    "export type Kennzahl = " + " | ".join(f'"{k}"' for k in ["elev", "meanElev", "coast", "birth", "age", "alc", "obes", "smoke", "fert", "docs", "net", "airports", "rail", "unemp"]) + ";",
    "export const KENNZAHLEN: Record<string, Partial<Record<Kennzahl, number>>> = {",
]
for k in sorted(out):
    lines.append(f"  {k}: {json.dumps(out[k], separators=(',', ':'))},")
lines.append("};")
open(os.path.join(ROOT, "lib/data/kennzahlen.ts"), "w").write("\n".join(lines) + "\n")
